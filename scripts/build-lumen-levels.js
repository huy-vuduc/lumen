// Builds lumen/lumen-levels-data.js one chapter at a time from lumen-chapters.js.
// Chapters already in the data file are kept exactly as they are, so adding a
// chapter or changing the generator never alters chambers players have seen.
// Only chapters missing from the file are generated; to regenerate an existing
// one, name it:
//   node scripts/build-lumen-levels.js                 builds missing chapters
//   node scripts/build-lumen-levels.js --rebuild 3,7   also regenerates chapters 3 and 7
//   node scripts/build-lumen-levels.js --rebuild all   regenerates every chapter
// Hint solutions (lumen-solutions-data.js) are refreshed afterwards.
// Every chamber, kept or new, is checked (unsolved at start, minMoves >= 1) and
// listed in a difficulty table: minimum moves + spare / rotatable mirrors, the
// mechanics present (F stone, S splitter, L filter, P portal, D dark ring) and
// "~n" when a new seed needed n relaxation steps.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', 'lumen');
const dataFile = path.join(root, 'lumen-levels-data.js');
global.LumenEngine = require(path.join(root, 'lumen-engine.js'));
global.LumenLevelGenerator = require(path.join(root, 'lumen-level-generator.js'));
const chapters = require(path.join(root, 'lumen-chapters.js'));
const existing = fs.existsSync(dataFile) ? require(dataFile) : [];

const rebuildArg = process.argv[process.argv.indexOf('--rebuild') + 1];
const rebuild = new Set(
  process.argv.includes('--rebuild')
    ? rebuildArg === 'all' ? chapters.CHAPTERS.map((c) => c.id) : String(rebuildArg).split(',').map(Number)
    : [],
);

let ok = true;
let relaxed = 0;
let built = 0;
const data = [];
for (const chapter of chapters.CHAPTERS) {
  const kept = existing[chapter.id - 1];
  const keep = !rebuild.has(chapter.id) && Array.isArray(kept) && kept.length === chapters.LEVELS_PER_CHAPTER;
  const row = [];
  const levels = [];
  const started = Date.now();
  for (let n = 1; n <= chapters.LEVELS_PER_CHAPTER; n++) {
    try {
      const level = keep ? kept[n - 1] : chapters.level(chapter.id, n);
      if (LumenEngine.trace(level, level.mirrors.map((m) => m.type)).solved || level.minMoves < 1) ok = false;
      const rotatable = level.mirrors.filter((m) => !m.fixed).length;
      const marks = [
        level.mirrors.some((m) => m.fixed) ? 'F' : '',
        level.splitters.length ? 'S' : '',
        level.filters.length ? 'L' : '',
        level.portals.length ? 'P' : '',
        level.targets.some((t) => t.color === 0) ? 'D' : '',
      ].join('');
      if (level.relaxed) relaxed++;
      row.push(`${level.minMoves}+${level.extraMoves}/${rotatable}${marks ? ' ' + marks : ''}${level.relaxed ? ' ~' + level.relaxed : ''}`);
      delete level.relaxed;
      levels.push(level);
    } catch (err) {
      ok = false;
      row.push('FAIL');
    }
  }
  if (!keep) built++;
  data.push(levels);
  const note = keep ? 'kept' : `built in ${Date.now() - started} ms`;
  console.log(`Ch${String(chapter.id).padStart(2)} ${chapter.name.en.padEnd(14)} ${row.join(' | ')}  [${note}]`);
}

if (relaxed) console.log(`${relaxed} chamber(s) needed a relaxed spec`);
if (!ok) { console.log('PROBLEM FOUND'); process.exit(1); }
if (!built) {
  console.log(`Nothing to build: all ${data.length} chapters kept`);
} else {
  const body = data.map((levels) => `  [\n${levels.map((l) => `    ${JSON.stringify(l)}`).join(',\n')},\n  ]`).join(',\n');
  const file = `// Generated by scripts/build-lumen-levels.js from lumen-chapters.js; do not edit.\n// LumenLevelsData[chapter - 1][chamber - 1] is a ready-to-play level.\nconst LumenLevelsData = [\n${body},\n];\n\nif (typeof module !== 'undefined') module.exports = LumenLevelsData;\n`;
  fs.writeFileSync(dataFile, file);
  console.log(`Wrote ${dataFile}: ${built} chapter(s) built, ${data.length - built} kept (${Math.round(file.length / 1024)} KB)`);
}
// Hint solutions follow the chamber data; chapters left as they were keep theirs.
require('./build-lumen-solutions.js');
