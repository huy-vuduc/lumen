// Builds lumen/lumen-solutions-data.js: for every chamber in
// lumen-levels-data.js, the smallest set of mirror indexes to turn so the
// chamber is solved. The game uses it for the "reveal a mirror" hint.
// Stored solutions are kept as long as they still solve their chamber in
// minMoves turns, so only new or rebuilt chapters are solved again.
//   node scripts/build-lumen-solutions.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', 'lumen');
const dataFile = path.join(root, 'lumen-solutions-data.js');
const LumenEngine = require(path.join(root, 'lumen-engine.js'));
const levels = require(path.join(root, 'lumen-levels-data.js'));
const existing = fs.existsSync(dataFile) ? require(dataFile) : [];

function stillValid(level, flips) {
  if (!Array.isArray(flips) || flips.length !== level.minMoves) return false;
  const types = level.mirrors.map((m) => m.type);
  for (const i of flips) {
    if (!level.mirrors[i] || level.mirrors[i].fixed) return false;
    types[i] = LumenEngine.toggle(types[i]);
  }
  return LumenEngine.trace(level, types).solved;
}

let solved = 0;
let ok = true;
const data = levels.map((chapter, c) => chapter.map((level, n) => {
  const kept = existing[c] && existing[c][n];
  if (stillValid(level, kept)) return kept;
  const flips = LumenEngine.solve(level);
  if (!flips || flips.length !== level.minMoves) { ok = false; console.log(`Ch${c + 1}/${n + 1}: no solution in ${level.minMoves} turns`); }
  solved++;
  return flips || [];
}));

if (!ok) { console.log('PROBLEM FOUND'); process.exit(1); }
const body = data.map((chapter) => `  [${chapter.map((f) => JSON.stringify(f)).join(', ')}]`).join(',\n');
const file = `// Generated by scripts/build-lumen-solutions.js from lumen-levels-data.js; do not edit.\n// LumenSolutionsData[chapter - 1][chamber - 1] lists the mirrors to turn.\nconst LumenSolutionsData = [\n${body},\n];\n\nif (typeof module !== 'undefined') module.exports = LumenSolutionsData;\n`;
if (!fs.existsSync(dataFile) || fs.readFileSync(dataFile, 'utf8') !== file) {
  fs.writeFileSync(dataFile, file);
  console.log(`Wrote ${dataFile}: ${solved} chamber(s) solved`);
} else {
  console.log('Solutions up to date');
}
